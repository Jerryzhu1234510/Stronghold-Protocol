export function supportReleaseRows(catalog, bonds) {
  return Object.values(catalog || {}).filter(op => op.ready).map(op => ({
    id: op.charId, name: op.name, bonds: (op.bonds || []).map(id => bonds?.[id]?.name || id).join('、'),
  }));
}
